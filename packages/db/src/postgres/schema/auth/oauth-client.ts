import { boolean, jsonb, pgTable, text, timestamp } from "drizzle-orm/pg-core";
import { user } from "./core.ts";

export const oauthClient = pgTable("oauth_client", {
  id: text("id").primaryKey(),
  clientId: text("client_id").notNull().unique("oauth_client_client_id_unique"),
  clientSecret: text("client_secret"),
  disabled: boolean("disabled").default(false),
  skipConsent: boolean("skip_consent"),
  enableEndSession: boolean("enable_end_session"),
  subjectType: text("subject_type"),
  scopes: jsonb("scopes"),
  userId: text("user_id").references(() => user.id, { onDelete: "cascade" }),
  createdAt: timestamp("created_at", { mode: "date", precision: 3, withTimezone: true }),
  updatedAt: timestamp("updated_at", { mode: "date", precision: 3, withTimezone: true }),
  name: text("name"),
  uri: text("uri"),
  icon: text("icon"),
  contacts: jsonb("contacts"),
  tos: text("tos"),
  policy: text("policy"),
  softwareId: text("software_id"),
  softwareVersion: text("software_version"),
  softwareStatement: text("software_statement"),
  redirectUris: jsonb("redirect_uris").notNull(),
  postLogoutRedirectUris: jsonb("post_logout_redirect_uris"),
  tokenEndpointAuthMethod: text("token_endpoint_auth_method"),
  grantTypes: jsonb("grant_types"),
  responseTypes: jsonb("response_types"),
  public: boolean("public"),
  type: text("type"),
  requirePKCE: boolean("require_pkce"),
  referenceId: text("reference_id"),
  metadata: jsonb("metadata"),
});
